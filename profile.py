"""Turn a collection selection into an MO2 profile. Qt-free.

* Mod priority comes from the curator's before/after rules (they always
  win); category, then name, only break ties. Category separators are
  inserted wherever the category changes, so a rule that forces a mod out of
  its block produces a second "Category (2)" separator instead of being
  broken.
* plugins.txt / loadorder.txt follow the curator's plugin list.
* A file-conflict report lists overwrites that no curator rule decided.
"""

from __future__ import annotations

import heapq
import os
import shutil
from dataclasses import dataclass, field
from typing import Dict, Iterable, List, Optional, Set, Tuple

from .collection import Collection
from .installer import long_path

HEADER = "# This file was automatically generated by Mod Organizer."

# A conventional Skyrim install order for Nexus categories; anything not
# listed sorts alphabetically between Miscellaneous and Patches.
CATEGORY_ORDER = [
    "Modders Resources", "Utilities", "Bug Fixes", "User Interface", "Gameplay",
    "Skills and Leveling", "Combat", "Stealth", "Magic - Gameplay", "Magic - Spells & Enchantments",
    "Guilds/Factions", "Quests and Adventures", "Dungeons", "Locations - New",
    "Cities, Towns, Villages, and Hamlets", "Buildings", "Player homes", "NPC",
    "Followers & Companions", "Creatures and Mounts", "Races, Classes, and Birthsigns",
    "Character Presets", "Body, Face, and Hair", "Hair and Face Models", "Models and Textures",
    "Armour", "Weapons", "Weapons and Armour", "Clothing and Accessories",
    "Items and Objects - Player", "Items and Objects - World", "Environmental",
    "Visuals and Graphics", "Lighting", "Weather", "Animation", "Audio", "Sound and Music",
    "Immersion", "Overhauls", "Presets - ENB and ReShade", "Miscellaneous",
]
PATCHES_LAST = ["Patches"]
BASE_MASTERS = ["Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm"]


def category_rank(category: str) -> Tuple[int, str]:
    lowered = (category or "").lower()
    for i, name in enumerate(CATEGORY_ORDER):
        if name.lower() == lowered:
            return (i, "")
    if lowered in (p.lower() for p in PATCHES_LAST):
        return (len(CATEGORY_ORDER) + 2, "")
    return (len(CATEGORY_ORDER) + 1, lowered or "~")


@dataclass
class OrderResult:
    keys: List[str]                       # lowest priority first
    cycles: List[str] = field(default_factory=list)   # keys placed despite a rule cycle
    rule_edges: int = 0


def build_order(coll: Collection, selected: Set[str]) -> OrderResult:
    mods = coll.by_key()
    nodes = [k for k in selected if k in mods]
    succ: Dict[str, Set[str]] = {k: set() for k in nodes}
    indeg: Dict[str, int] = {k: 0 for k in nodes}
    edges = 0
    for rule in coll.rules:
        a, b = rule.source, rule.reference
        if a not in succ or b not in succ or a == b:
            continue
        if rule.type == "after":        # source loads after (overwrites) reference
            lo, hi = b, a
        elif rule.type == "before":
            lo, hi = a, b
        else:
            continue
        if hi not in succ[lo]:
            succ[lo].add(hi)
            indeg[hi] += 1
            edges += 1

    # Vortex install phases decide install sequence, not overwrite priority,
    # so they only break ties; leading with them splits every category block.
    def key(k: str):
        m = mods[k]
        return (category_rank(m.category), m.name.lower(), m.phase, k)

    # Kahn's algorithm, but stay in the current category while the rules
    # allow it: this keeps each category in as few blocks as possible.
    ready: Dict[Tuple[int, str], List[Tuple]] = {}

    def push(k: str) -> None:
        heapq.heappush(ready.setdefault(category_rank(mods[k].category), []), key(k))

    for k in nodes:
        if indeg[k] == 0:
            push(k)
    order: List[str] = []
    current: Optional[Tuple[int, str]] = None
    while any(ready.values()):
        if current is None or not ready.get(current):
            current = min(c for c, h in ready.items() if h)
        k = heapq.heappop(ready[current])[-1]
        order.append(k)
        for nxt in succ[k]:
            indeg[nxt] -= 1
            if indeg[nxt] == 0:
                push(nxt)
    cycles = sorted((k for k in nodes if k not in set(order)), key=key)
    order += cycles
    return OrderResult(order, cycles, edges)


@dataclass
class ProfileEntry:
    name: str           # MO2 mod folder name (separators end in _separator)
    separator: bool = False
    enabled: bool = True


def with_separators(order: List[str], coll: Collection, folder_of: Dict[str, str],
                    use_separators: bool) -> List[ProfileEntry]:
    mods = coll.by_key()
    out: List[ProfileEntry] = []
    seen: Dict[str, int] = {}
    current = None
    for k in order:
        category = mods[k].category or "Uncategorized"
        if use_separators and category != current:
            current = category
            seen[category] = seen.get(category, 0) + 1
            label = category if seen[category] == 1 else f"{category} ({seen[category]})"
            safe = "".join("_" if ch in '<>:"/\\|?*' else ch for ch in label)
            out.append(ProfileEntry(f"{safe}_separator", separator=True, enabled=False))
        out.append(ProfileEntry(folder_of[k]))
    return out


def ensure_separator_folders(mods_path: str, entries: List[ProfileEntry]) -> int:
    made = 0
    for e in entries:
        if not e.separator:
            continue
        path = os.path.join(mods_path, e.name)
        if not os.path.isdir(path):
            os.makedirs(path)
            with open(os.path.join(path, "meta.ini"), "w", encoding="utf-8", newline="\r\n") as h:
                h.write(SEPARATOR_META)
            made += 1
    return made


