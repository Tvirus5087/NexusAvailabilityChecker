def plugins_in(mod_dirs: Iterable[str]) -> Dict[str, str]:
    """lowercase plugin name -> real file name, from the top of each mod."""
    out: Dict[str, str] = {}
    for d in mod_dirs:
        try:
            for name in os.listdir(d):
                if name.lower().endswith((".esp", ".esm", ".esl")):
                    out.setdefault(name.lower(), name)
        except OSError:
            continue
    return out


@dataclass
class PluginPlan:
    order: List[Tuple[str, bool]]     # (real name, enabled)
    missing: List[str]                # in curator list, not provided by any mod
    extra: List[str]                  # provided by mods, not in curator list (appended)


def plan_plugins(coll: Collection, available: Dict[str, str], game_data: Dict[str, str]) -> PluginPlan:
    base = {m.lower() for m in BASE_MASTERS}
    order: List[Tuple[str, bool]] = []
    used: Set[str] = set()
    missing: List[str] = []
    for name, enabled in coll.plugins:
        lowered = name.lower()
        if lowered in base or lowered in used:
            continue
        real = available.get(lowered) or game_data.get(lowered)
        if real is None:
            missing.append(name)
            continue
        if lowered in game_data and lowered not in available and lowered.startswith("cc"):
            continue    # Creation Club files load from Skyrim.ccc
        order.append((real, enabled))
        used.add(lowered)
    extra = []
    for lowered, real in sorted(available.items()):
        if lowered not in used and lowered not in base:
            order.append((real, True))
            used.add(lowered)
            extra.append(real)
    # Masters first, as the game requires.
    masters = [p for p in order if p[0].lower().endswith(".esm")]
    rest = [p for p in order if not p[0].lower().endswith(".esm")]
    return PluginPlan(masters + rest, missing, extra)


