PROFILE_SKIP = {"modlist.txt", "plugins.txt", "loadorder.txt", "lockedorder.txt", "archives.txt"}


def write_profile(profiles_dir: str, profile_name: str, entries: List[ProfileEntry],
                  plugins: PluginPlan, copy_settings_from: str = "") -> str:
    path = os.path.join(profiles_dir, profile_name)
    if os.path.exists(path):
        raise FileExistsError(f"profile '{profile_name}' already exists")
    os.makedirs(path)
    if copy_settings_from and os.path.isdir(copy_settings_from):
        for name in os.listdir(copy_settings_from):
            src = os.path.join(copy_settings_from, name)
            if os.path.isfile(src) and name.lower() not in PROFILE_SKIP:
                shutil.copy2(src, os.path.join(path, name))
    if not os.path.isfile(os.path.join(path, "settings.ini")):
        with open(os.path.join(path, "settings.ini"), "w", encoding="utf-8", newline="\r\n") as h:
            h.write("[General]\nLocalSaves=false\nLocalSettings=false\nAutomaticArchiveInvalidation=false\n")
    # modlist.txt lists the highest-priority mod first.
    lines = [HEADER] + [("-" if e.separator or not e.enabled else "+") + e.name for e in reversed(entries)]
    with open(os.path.join(path, "modlist.txt"), "w", encoding="utf-8", newline="\r\n") as h:
        h.write("\n".join(lines) + "\n")
    with open(os.path.join(path, "plugins.txt"), "w", encoding="utf-8", newline="\r\n") as h:
        h.write("\n".join([HEADER] + [("*" if on else "") + name for name, on in plugins.order]) + "\n")
    with open(os.path.join(path, "loadorder.txt"), "w", encoding="utf-8", newline="\r\n") as h:
        h.write("\n".join([HEADER] + BASE_MASTERS + [name for name, _on in plugins.order]) + "\n")
    return path


