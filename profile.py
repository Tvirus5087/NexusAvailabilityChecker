_IGNORE_TOP = {"meta.ini", "root", "fomod"}


def unruled_conflicts(coll: Collection, order: List[str], folder_of: Dict[str, str],
                      mods_path: str, limit: int = 40) -> Tuple[int, List[Tuple[str, str, int, str]]]:
    """(total overwritten files, [(winner, loser, files, example)]) for pairs
    with no before/after rule between them. Loose files only: BSA contents
    are not inspected."""
    ruled: Set[Tuple[str, str]] = set()
    for rule in coll.rules:
        if rule.type in ("after", "before") and rule.source and rule.reference:
            ruled.add((rule.source, rule.reference))
            ruled.add((rule.reference, rule.source))
    owner: Dict[str, str] = {}
    pairs: Dict[Tuple[str, str], List[str]] = {}
    total = 0
    for k in order:
        root = long_path(os.path.join(mods_path, folder_of[k]))
        for dirpath, dirs, files in os.walk(root):
            if dirpath == root:
                dirs[:] = [d for d in dirs if d.lower() not in _IGNORE_TOP]
            for name in files:
                rel = os.path.relpath(os.path.join(dirpath, name), root).lower()
                if rel in _IGNORE_TOP:
                    continue
                prev = owner.get(rel)
                if prev is not None and prev != k:
                    total += 1
                    if (k, prev) not in ruled:
                        pairs.setdefault((k, prev), []).append(rel)
                owner[rel] = k
    mods = coll.by_key()
    report = sorted(((mods[w].name, mods[l].name, len(files), files[0]) for (w, l), files in pairs.items()),
                    key=lambda t: -t[2])
    return total, report[:limit]


SEPARATOR_META = "[General]\nmodid=0\nversion=\nnewestVersion=\ncategory=0\ninstallationFile=\n"


def prune_separators(mods_path: str, profiles_dir: str) -> List[str]:
    """Delete separator folders this plugin created that no profile lists."""
    used: Set[str] = set()
    try:
        for profile in os.listdir(profiles_dir):
            try:
                with open(os.path.join(profiles_dir, profile, "modlist.txt"), "r",
                          encoding="utf-8", errors="replace") as h:
                    for line in h:
                        used.add(line.strip()[1:].lower())
            except OSError:
                continue
    except OSError:
        return []
    removed = []
    for name in os.listdir(mods_path):
        if not name.endswith("_separator") or name.lower() in used:
            continue
        folder = os.path.join(mods_path, name)
        try:
            if os.listdir(folder) != ["meta.ini"]:
                continue
            with open(os.path.join(folder, "meta.ini"), "r", encoding="utf-8") as h:
                if h.read().replace("\r\n", "\n") != SEPARATOR_META:
                    continue   # not one of ours (or the user customised it)
            shutil.rmtree(folder)
            removed.append(name)
        except OSError:
            continue
    return removed
